/**
 * 認識結果の文面から読点「、」を推測して付ける（話の間の長さには頼らない）。
 * 迷うところには付けない（付け過ぎは読みにくく、後から消すのも手間なため）。
 *
 *  1. 文頭の接続詞・副詞のあと:   「しかし経過は良好です」→「しかし、経過は良好です」
 *  2. 理由・逆接で節が終わるとき: 「痛みますが歩けます」→「痛みますが、歩けます」
 *  3. 「〜するため」のあと:       「経過を見るため再診します」→「経過を見るため、再診します」
 */

const MARK = '、。！？!?\\n';

/** 文頭（または文末記号の直後）に来る接続詞・副詞 */
const LEAD_WORDS = [
  'しかし',
  'ただし',
  'そして',
  'それから',
  'さらに',
  'ところで',
  'したがって',
  'そのため',
  'つまり',
  'なので',
  'ですので',
  'そのうえ',
  'ちなみに',
  'たとえば',
  '例えば',
  'まず',
  '次に',
  '最後に',
  'また',
  'なお',
  'ただ',
];
const LEAD = new RegExp(
  `(^|[。？！\\n])(${LEAD_WORDS.join('|')})(?![${MARK}\\s]|[はもをがにのでとるりしすせれ])`,
  'g'
);

/** 節の終わり（逆接・理由）。直前が述語の形のときだけ */
const CLAUSE_END: RegExp[] = [
  // 〜ますが／ですが／ませんが／でしたが／ましたが
  new RegExp(`(ますが|ですが|ませんが|でしたが|ましたが)(?![${MARK}\\s])(?=.)`, 'g'),
  // 〜けど／けれど／けれども
  new RegExp(
    `(?<=[るたいうくすだんしきぎむぶぐぬつ])(けれども|けれど|けど)(?![${MARK}\\s])(?=.)`,
    'g'
  ),
  // 〜ので（「のでしょう」「のです」は文末なので除く）
  new RegExp(`(?<=[るたいうくすだんしきぎむぶぐぬつ])ので(?![${MARK}\\sしす])(?=.)`, 'g'),
  // 〜ですから／ますから／たから／ないから（「〜してから」は除く）
  new RegExp(`(?<=ます|です|ました|でした|ない|だ|た)から(?![${MARK}\\sこで])(?=.)`, 'g'),
  // 〜するため（「ために」「ための」は除く）
  new RegExp(`(?<=[るたい])ため(?![${MARK}\\sにのでは])(?=.)`, 'g'),
];

export function inferCommas(text: string): string {
  let out = text.replace(LEAD, '$1$2、');
  for (const re of CLAUSE_END) out = out.replace(re, '$&、');
  return out;
}
